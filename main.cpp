#include <string>
#include <vector>

void swap_values() {
    int a = 5, b = 11;
    int tmp = a;
    a = b;
    b = tmp;
    (void)a;
    (void)b;
}

void center_digit() {
    int n = 98765;
    int digits = 0;
    int temp = n;
    while (temp > 0) { digits += 1; temp /= 10; }
    for (int i = 1; i < digits / 2; ++i) n /= 10;
    int center = n % 10;
    (void)center;
}

void digit_sum() {
    int n = 9081;
    int total = 0;
    while (n > 0) {
        total += n % 10;
        n /= 10;
    }
    (void)total;
}

void count_vowels() {
    std::string text = "prism bridge";
    int vowels = 0;
    for (std::size_t i = 0; i < text.size(); ++i) {
        char ch = text[i];
        if (ch == 'a' || ch == 'e' || ch == 'i' || ch == 'o' || ch == 'u') vowels += 1;
    }
    (void)vowels;
}

extern "C" int placid_hollow();
extern "C" void prime_delta();
extern "C" void vivid_cove();
extern "C" void swift_crescent();
extern "C" void noble_kite();

int main() {
    swap_values();
    center_digit();
    digit_sum();
    count_vowels();
    prime_delta();
    vivid_cove();
    swift_crescent();
    noble_kite();
    return placid_hollow();
}
